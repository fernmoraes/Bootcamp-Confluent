-- Camada 0/3 — Esquema de origem do pipeline de pagamentos (Postgres/Neon).
-- Reexecutável: recria tudo. NÃO rodar depois que o conector CDC estiver ativo
-- (o teardown.sh derruba o conector antes).
--
-- Dados 100% sintéticos. Nenhum PAN real: só máscara + últimos 4 dígitos.

DROP PUBLICATION IF EXISTS desafio_pub;
DROP TABLE IF EXISTS transactions, cards, accounts, merchants, customers CASCADE;

CREATE TABLE customers (
    customer_id  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    text         NOT NULL,   -- PII
    email        text         NOT NULL,   -- PII
    phone        text         NOT NULL,   -- PII
    birth_date   date         NOT NULL,   -- PII
    city         text         NOT NULL,
    created_at   timestamptz  NOT NULL
);

CREATE TABLE accounts (
    account_id    integer        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   integer        NOT NULL REFERENCES customers (customer_id),
    account_type  text           NOT NULL CHECK (account_type IN ('CHECKING', 'SAVINGS', 'CREDIT')),
    status        text           NOT NULL CHECK (status IN ('ACTIVE', 'BLOCKED', 'CLOSED')),
    risk_tier     text           NOT NULL CHECK (risk_tier IN ('LOW', 'MEDIUM', 'HIGH')),
    balance       numeric(15, 2) NOT NULL,
    currency      char(3)        NOT NULL DEFAULT 'BRL',
    opened_at     timestamptz    NOT NULL,
    updated_at    timestamptz    NOT NULL DEFAULT now()
);

CREATE TABLE cards (
    card_id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        integer     NOT NULL REFERENCES accounts (account_id),
    card_number_mask  text        NOT NULL,   -- PCI: apenas máscara + last4
    brand             text        NOT NULL CHECK (brand IN ('VISA', 'MASTERCARD', 'ELO')),
    status            text        NOT NULL CHECK (status IN ('ACTIVE', 'BLOCKED', 'EXPIRED')),
    expires_on        date        NOT NULL,
    issued_at         timestamptz NOT NULL
);

CREATE TABLE merchants (
    merchant_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text    NOT NULL,
    mcc          char(4) NOT NULL,   -- Merchant Category Code
    category     text    NOT NULL,
    city         text    NOT NULL,
    country      char(2) NOT NULL DEFAULT 'BR'
);

CREATE TABLE transactions (
    transaction_id  bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id         integer        NOT NULL REFERENCES cards (card_id),
    account_id      integer        NOT NULL REFERENCES accounts (account_id),
    merchant_id     integer        NOT NULL REFERENCES merchants (merchant_id),
    amount          numeric(15, 2) NOT NULL CHECK (amount > 0),
    currency        char(3)        NOT NULL DEFAULT 'BRL',
    status          text           NOT NULL CHECK (status IN ('APPROVED', 'DECLINED')),
    txn_ts          timestamptz    NOT NULL   -- tempo do evento (event time no Flink)
);

CREATE INDEX idx_transactions_card_ts ON transactions (card_id, txn_ts);

-- before/after completos no UPDATE e no DELETE (op=u / op=d)
ALTER TABLE customers    REPLICA IDENTITY FULL;
ALTER TABLE accounts     REPLICA IDENTITY FULL;
ALTER TABLE cards        REPLICA IDENTITY FULL;
ALTER TABLE merchants    REPLICA IDENTITY FULL;
ALTER TABLE transactions REPLICA IDENTITY FULL;

-- Publication explícita (o conector roda com menor privilégio e não a cria)
CREATE PUBLICATION desafio_pub
    FOR TABLE customers, accounts, cards, merchants, transactions;
